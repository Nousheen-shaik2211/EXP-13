import os
from google.colab import userdata
from langchain_core.documents import Document
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import RunnablePassthrough
from langchain_core.output_parsers import StrOutputParser
from langchain_community.vectorstores import FAISS
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_google_genai import ChatGoogleGenerativeAI

# API Key
os.environ["GOOGLE_API_KEY"] = userdata.get("GOOGLE_API_KEY")

# Climate change text (reuse Experiment 12 text here)
text = """
Climate change is mainly caused by greenhouse gases released by
burning fossil fuels, deforestation, and industrial activities.
It causes rising temperatures, melting polar ice caps, rising sea
levels, extreme weather events, and threats to ecosystems.
"""

# Split text into chunks
from langchain_text_splitters import RecursiveCharacterTextSplitter
docs = RecursiveCharacterTextSplitter(
    chunk_size=150, chunk_overlap=20
).create_documents([text])

# Create FAISS vector store
embeddings = HuggingFaceEmbeddings(
    model_name="sentence-transformers/all-MiniLM-L6-v2"
)
vectorstore = FAISS.from_documents(docs, embeddings)

# Retriever: top 2 relevant chunks
retriever = vectorstore.as_retriever(search_kwargs={"k": 2})

# Prompt template
prompt = ChatPromptTemplate.from_template("""
Answer using ONLY the provided context.
If the answer is not in the context, say "I don't know".

Context:
{context}

Question: {question}
Answer:
""")

# Gemini LLM
llm = ChatGoogleGenerativeAI(model="gemini-3.7-flash",
                             temperature=0)

# LCEL RAG chain
rag_chain = (
    {
        "context": retriever,
        "question": RunnablePassthrough()
    }
    | prompt
    | llm
    | StrOutputParser()
)

# Test with two questions
for q in [
    "What causes climate change?",
    "What are the effects of climate change?"
]:
    print("\nQuestion:", q)
    print("Answer:", rag_chain.invoke(q))

    print("Retrieved Chunks:")
    for doc in retriever.invoke(q):
        print("-", doc.page_content)